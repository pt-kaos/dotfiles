#!/bin/bash
# Regenerate every per-app colour file from theme/palette.sh, then reload.
#   ./apply.sh          generate + reload waybar & hyprland
#   ./apply.sh --boot   generate only (for hyprland autostart; nothing to reload)
set -u

THEME_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
DOTFILES="$(cd -- "$THEME_DIR/.." && pwd)"
CFG="${XDG_CONFIG_HOME:-$HOME/.config}"

# shellcheck source=palette.sh
. "$THEME_DIR/palette.sh"

# palette.sh keeps a leading '#' on colours (editor swatches); strip it here so
# each generator can add the prefix its target format wants.
for _v in BG BG_ALT FG FG_DIM ACCENT ACCENT_DIM WARNING CRITICAL \
         BORDER_ACTIVE_A BORDER_ACTIVE_B BORDER_INACTIVE \
         ANSI_BLUE ANSI_MAGENTA ANSI_CYAN; do
    printf -v "$_v" '%s' "${!_v#\#}"
done
unset _v

BOOT=0
[ "${1:-}" = "--boot" ] && BOOT=1
say() { [ "$BOOT" = 1 ] || printf '  %s\n' "$*"; }

# hex "rrggbb" -> "r, g, b"
rgb_triplet() { printf '%d, %d, %d' "0x${1:0:2}" "0x${1:2:2}" "0x${1:4:2}"; }

GEN="AUTO-GENERATED by theme/apply.sh from theme/palette.sh — do not edit"

# ── waybar ────────────────────────────────────────────────────────────────────
cat > "$DOTFILES/waybar/colors.css" <<EOF
/* $GEN */
@define-color bar-bg     rgba($(rgb_triplet "$BG"), $BG_ALPHA);
@define-color capsule-bg rgba(255, 255, 255, 0.05);
@define-color fg         #$FG;
@define-color dim-fg     #$FG_DIM;
@define-color accent     #$ACCENT;
@define-color accent-dim #$ACCENT_DIM;
@define-color warning    #$WARNING;
@define-color critical   #$CRITICAL;
EOF
say "waybar/colors.css"

# ── hyprland (borders / shadow) ───────────────────────────────────────────────
cat > "$DOTFILES/hypr/awesomeconf/colors.lua" <<EOF
-- $GEN
return {
    bg              = 'rgb($BG)',
    bg_alt          = 'rgb($BG_ALT)',
    fg              = 'rgb($FG)',
    fg_dim          = 'rgb($FG_DIM)',
    accent          = 'rgb($ACCENT)',
    accent_dim      = 'rgb($ACCENT_DIM)',
    warning         = 'rgb($WARNING)',
    critical        = 'rgb($CRITICAL)',
    border_active   = { 'rgba(${BORDER_ACTIVE_A}ee)', 'rgba(${BORDER_ACTIVE_B}ee)' },
    border_inactive = 'rgba(${BORDER_INACTIVE}aa)',
    shadow          = 0xee$BG,
}
EOF
say "hypr/awesomeconf/colors.lua"

# ── hyprlock (hyprlang vars, sourced by hyprlock.conf) ────────────────────────
cat > "$DOTFILES/hypr/colors.conf" <<EOF
# $GEN
\$bg       = rgb($BG)
\$bg_alt   = rgb($BG_ALT)
\$fg       = rgb($FG)
\$fg_dim   = rgb($FG_DIM)
\$accent   = rgb($ACCENT)
\$critical = rgb($CRITICAL)
EOF
say "hypr/colors.conf"

# ── alacritty ─────────────────────────────────────────────────────────────────
cat > "$DOTFILES/alacritty/colors.toml" <<EOF
# $GEN
[colors.primary]
background = "#$BG"
foreground = "#$FG"

[colors.cursor]
cursor = "#$ACCENT"
text   = "#$BG"

[colors.selection]
background = "#$ACCENT_DIM"
text       = "#$FG"

[colors.normal]
black   = "#$BG"
red     = "#$CRITICAL"
green   = "#$ACCENT"
yellow  = "#$WARNING"
blue    = "#$ANSI_BLUE"
magenta = "#$ANSI_MAGENTA"
cyan    = "#$ANSI_CYAN"
white   = "#$FG"

[colors.bright]
black   = "#$FG_DIM"
red     = "#$CRITICAL"
green   = "#$ACCENT"
yellow  = "#$WARNING"
blue    = "#$ANSI_BLUE"
magenta = "#$ANSI_MAGENTA"
cyan    = "#$ANSI_CYAN"
white   = "#$FG"
EOF
say "alacritty/colors.toml"

# ── fish ──────────────────────────────────────────────────────────────────────
cat > "$DOTFILES/fish/conf.d/zz-theme.fish" <<EOF
# $GEN
set -g fish_color_normal $FG
set -g fish_color_command $ACCENT
set -g fish_color_keyword $ACCENT
set -g fish_color_param $FG
set -g fish_color_option $FG_DIM
set -g fish_color_quote $WARNING
set -g fish_color_redirection $ACCENT
set -g fish_color_end $ACCENT_DIM
set -g fish_color_error $CRITICAL
set -g fish_color_comment $FG_DIM
set -g fish_color_operator $ACCENT
set -g fish_color_escape $ACCENT
set -g fish_color_autosuggestion $FG_DIM
set -g fish_color_selection --background=$ACCENT_DIM
set -g fish_color_search_match --background=$ACCENT_DIM
set -g fish_pager_color_prefix $ACCENT
set -g fish_pager_color_completion $FG
set -g fish_pager_color_description $FG_DIM
set -g fish_pager_color_selected_background --background=$ACCENT_DIM
EOF
say "fish/conf.d/zz-theme.fish"

# ── GTK 3 + 4 (dark; this is what fixes pavucontrol) ──────────────────────────
write_gtk() {
    local dir="$1"
    mkdir -p "$dir"
    cat > "$dir/settings.ini" <<EOF
# $GEN
[Settings]
gtk-theme-name=$GTK_THEME
gtk-icon-theme-name=$ICON_THEME
gtk-cursor-theme-name=$CURSOR_THEME
gtk-cursor-theme-size=$CURSOR_SIZE
gtk-font-name=$FONT_NAME
gtk-application-prefer-dark-theme=1
gtk-xft-antialias=1
gtk-xft-hinting=1
gtk-xft-hintstyle=hintslight
gtk-xft-rgba=rgb
EOF
}
write_gtk "$CFG/gtk-3.0"
write_gtk "$CFG/gtk-4.0"
say "gtk-3.0/settings.ini, gtk-4.0/settings.ini"

# ── gsettings (portal / libadwaita / GTK4 default) ───────────────────────────
if command -v gsettings >/dev/null; then
    gi() { gsettings set org.gnome.desktop.interface "$1" "$2" 2>/dev/null; }
    gi color-scheme 'prefer-dark'
    gi gtk-theme    "$GTK_THEME"
    gi icon-theme   "$ICON_THEME"
    gi cursor-theme "$CURSOR_THEME"
    gi cursor-size  "$CURSOR_SIZE"
    gi font-name    "$FONT_NAME"
    say "gsettings org.gnome.desktop.interface"
fi

# ── Qt / Kvantum (already dark; just pin the theme name) ─────────────────────
KVCFG="$CFG/Kvantum/kvantum.kvconfig"
if [ -f "$KVCFG" ]; then
    if grep -q '^theme=' "$KVCFG"; then
        sed -i "s/^theme=.*/theme=$KVANTUM_THEME/" "$KVCFG"
    else
        printf '[General]\ntheme=%s\n' "$KVANTUM_THEME" >> "$KVCFG"
    fi
    say "Kvantum theme=$KVANTUM_THEME"
fi

# ── reload live components ────────────────────────────────────────────────────
if [ "$BOOT" = 0 ]; then
    command -v hyprctl >/dev/null && hyprctl reload >/dev/null 2>&1 && say "hyprctl reload"
    pkill -x -SIGUSR2 waybar 2>/dev/null && say "waybar reloaded" || true
    printf 'theme applied. New terminals/GTK/Qt windows pick up the rest.\n'
fi
